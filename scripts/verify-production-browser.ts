import { loadEnvConfig } from "@next/env";
import { randomBytes } from "node:crypto";
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { getPrisma } from "@/lib/prisma";
import * as XLSX from "xlsx";
loadEnvConfig(process.cwd());
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || "C:/Program Files/WindowsApps/OpenAI.CodexPrimaryRuntime.v26-1123-915-0_26.1123.915.0_x64__3k8sg7r9htsxt/dependencies/node/node_modules/playwright");
const base = "http://localhost:3010";
async function main() {
  const db = getPrisma(), tag = `production-qa-${randomBytes(5).toString("hex")}`;
  const equipment = await db.equipment.findFirstOrThrow({ where: { status: "ACTIVE", code: "MCC_1" }, select: { id: true } });
  const ids: string[] = [];
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  const token = randomBytes(32).toString("hex");
  let batchId = "";
  try {
    const admin = await db.user.create({ data: { name: `${tag}-admin`, email: "", role: "ADMIN" } }); ids.push(admin.id);
    const operator = await db.user.create({ data: { name: `${tag}-operator`, email: "", role: "TICKET" } }); ids.push(operator.id);
    const operator2 = await db.user.create({ data: { name: `${tag}-operator2`, email: "", role: "USER" } }); ids.push(operator2.id);
    const technician = await db.user.create({ data: { name: `${tag}-CQ`, email: "", role: "SGQ" } }); ids.push(technician.id);
    await db.session.create({ data: { token, userId: admin.id, expiresAt: new Date(Date.now() + 3_600_000) } });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: "casa_sgq_session", value: token, url: base }]);
    const page = await context.newPage();
    page.on("pageerror", (e: Error) => console.error("Browser error", e.message));
    await page.goto(base + "/producao");
    await page.getByText("Novo lote", { exact: true }).click();
    const create = page.locator('form').filter({ has: page.locator('input[name="command"][value="create"]') });
    await create.locator('[name="reference"]').fill(tag);
    await create.locator('[name="lot"]').fill("QA");
    await create.locator('[name="equipmentId"]').selectOption(equipment.id);
    await create.getByRole("button", { name: "Criar lote" }).click();
    await page.waitForURL(/lote=/);
    batchId = new URL(page.url()).searchParams.get("lote")!;
    await page.locator('summary').filter({ hasText: "Registar atividade" }).click();
    const activity = page.locator('form').filter({ has: page.locator('input[name="command"][value="activity"]') }).first();
    await activity.locator(`[name="collaboratorId"][value="${operator.id}"]`).check();
    await activity.locator(`[name="collaboratorId"][value="${operator2.id}"]`).check();
    await activity.locator('[name="startedAt"]').fill("2026-11-25T08:30");
    await activity.locator('[name="endedAt"]').fill("2026-11-25T09:25");
    await activity.getByRole("button", { name: "Registar atividade" }).click();
    await activity.getByRole("status").filter({ hasText: "Registo guardado" }).waitFor();
    assert.equal(await db.productionActivity.count({ where: { batchId } }), 2);
    await activity.locator(`[name="collaboratorId"][value="${operator.id}"]`).check();
    await activity.locator('[name="startedAt"]').fill("2026-11-25T08:30");
    await activity.locator('[name="endedAt"]').fill("2026-11-25T09:25");
    await activity.getByRole("button", { name: "Registar atividade" }).click();
    await activity.getByRole("status").filter({ hasText: "já tem uma atividade" }).waitFor();
    assert.equal(await db.productionActivity.count({ where: { batchId } }), 2);
    await page.locator('summary').filter({ hasText: "Nova chamada de CQ" }).click();
    const cq = page.locator('form').filter({ has: page.locator('input[name="command"][value="quality"]') }).first();
    await cq.locator('[name="calledAt"]').fill("2026-11-25T09:35");
    await cq.locator('[name="arrivedAt"]').fill("2026-11-25T09:40");
    await cq.locator('[name="endedAt"]').fill("2026-11-25T09:50");
    await cq.locator('[name="technicianId"]').selectOption(technician.id);
    await cq.getByLabel("Houve paragem de produção?").check();
    await cq.locator('[name="stopStartedAt"]').fill("2026-11-25T09:38");
    await cq.locator('[name="stopEndedAt"]').fill("2026-11-25T09:46");
    await cq.getByRole("button", { name: "Registar chamada" }).click();
    await cq.getByRole("status").filter({ hasText: "Registo guardado" }).waitFor();
    const saved = await db.productionQualityCall.findFirstOrThrow({ where: { batchId } });
    assert.equal(saved.hasStop, true);
    assert.equal((saved.arrivedAt!.getTime() - saved.calledAt.getTime()) / 60_000, 5);
    await page.locator('article').first().waitFor();
    await cq.getByLabel("Houve paragem de produção?").uncheck();
    await cq.locator('[name="calledAt"]').fill("2026-11-25T10:00");
    await cq.locator('[name="arrivedAt"]').fill("2026-11-25T10:05");
    await cq.locator('[name="endedAt"]').fill("2026-11-25T10:10");
    await cq.locator('[name="technicianId"]').selectOption(technician.id);
    await cq.getByRole("button", { name: "Registar chamada" }).click();
    await page.locator('article').nth(1).waitFor();
    assert.equal(await db.productionQualityCall.count({ where: { batchId, hasStop: false } }), 1);
    while (await page.locator('details[open] > summary').count()) await page.locator('details[open] > summary').first().click();
    for (const [label, viewport] of [["desktop", { width: 1440, height: 1000 }], ["tablet", { width: 820, height: 1180 }], ["mobile", { width: 390, height: 844 }]] as const) {
      await page.setViewportSize(viewport);
      await page.screenshot({ path: `outputs/production-${label}.png`, fullPage: true });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${label}: page overflow`);
    }
    await page.locator('summary').filter({ hasText: "Quantidade, observações" }).click();
    const batchForm = page.locator('form').filter({ has: page.locator('input[name="command"][value="batch"]') });
    await batchForm.locator('[name="quantity"]').fill("511");
    await batchForm.locator('[name="status"]').selectOption("DONE");
    await batchForm.getByRole("button", { name: "Guardar lote" }).click();
    await page.getByRole("button", { name: "Conferir lote" }).waitFor();
    await page.getByRole("button", { name: "Conferir lote" }).click();
    await page.getByRole("button", { name: "Conferir lote" }).waitFor({ state: "detached" });
    assert.equal((await db.productionBatch.findUniqueOrThrow({ where: { id: batchId } })).status, "VERIFIED");
    const excel = await context.request.get(`${base}/api/producao/${batchId}/export?format=xlsx`);
    assert.equal(excel.status(), 200);
    const data = await excel.body();
    const workbook = XLSX.read(data, { type: "buffer" });
    assert.equal(workbook.SheetNames.length, 5);
    assert.equal(XLSX.utils.sheet_to_json(workbook.Sheets.Atividades).length, 2);
    assert.equal(XLSX.utils.sheet_to_json(workbook.Sheets.Qualidade).length, 2);
    writeFileSync("outputs/production-test.xlsx", data);
    const pdf = await context.request.get(`${base}/api/producao/${batchId}/export?format=pdf`);
    assert.equal(pdf.status(), 200);
    writeFileSync("outputs/production-test.pdf", await pdf.body());
    const post = await db.user.create({ data: { name: `${tag}-post`, email: "", role: "TICKET" } }); ids.push(post.id);
    const postToken = randomBytes(32).toString("hex");
    await db.session.create({ data: { token: postToken, userId: post.id, expiresAt: new Date(Date.now() + 3_600_000) } });
    await context.addCookies([{ name: "casa_sgq_session", value: postToken, url: base }]);
    assert.equal((await context.request.get(`${base}/api/producao/${batchId}/export?format=xlsx`)).status(), 404);
    await db.ticketEquipmentAccess.create({ data: { userId: post.id, equipmentId: equipment.id } });
    assert.equal((await context.request.get(`${base}/api/producao/${batchId}/export?format=xlsx`)).status(), 200);
    await context.addCookies([{ name: "casa_sgq_session", value: token, url: base }]);
    await page.goto(`${base}/producao?lote=${batchId}`);
    const reopen = page.locator('form').filter({ has: page.locator('input[name="command"][value="reopen"]') });
    await reopen.locator('[name="reason"]').fill("QA: testar reabertura e atividade em curso");
    await reopen.getByRole("button", { name: "Reabrir lote" }).click();
    await page.getByRole("button", { name: "Reabrir lote" }).waitFor({ state: "detached" });
    assert.equal((await db.productionBatch.findUniqueOrThrow({ where: { id: batchId } })).status, "OPEN");
    await page.locator('summary').filter({ hasText: "Registar atividade" }).click();
    const ongoing = page.locator('form').filter({ has: page.locator('input[name="command"][value="activity"]') }).first();
    await ongoing.locator(`[name="collaboratorId"][value="${operator.id}"]`).check();
    await ongoing.getByRole("button", { name: "Registar atividade" }).click();
    await page.getByRole("button", { name: "Terminar", exact: true }).waitFor();
    await page.getByRole("button", { name: "Terminar", exact: true }).click();
    await page.getByRole("button", { name: "Terminar", exact: true }).waitFor({ state: "detached" });
    assert.equal(await db.productionActivity.count({ where: { batchId, endedAt: null } }), 0);
    console.log("PASS: grouped activity, rejected overlaps, independent CQ waiting/work/stops, no-stop CQ, verification, XLSX/PDF, scoped post access and responsive screenshots.");
  } finally {
    await browser.close();
    const batchIds = (await db.productionBatch.findMany({ where: { reference: tag }, select: { id: true } })).map(x => x.id);
    await db.productionAudit.deleteMany({ where: { batchId: { in: batchIds } } });
    await db.productionQualityCall.deleteMany({ where: { batchId: { in: batchIds } } });
    await db.productionActivity.deleteMany({ where: { batchId: { in: batchIds } } });
    await db.productionBatch.deleteMany({ where: { id: { in: batchIds } } });
    await db.session.deleteMany({ where: { userId: { in: ids } } });
    await db.ticketEquipmentAccess.deleteMany({ where: { userId: { in: ids } } });
    await db.user.deleteMany({ where: { id: { in: ids } } });
    console.log("PASS: temporary test users, sessions and production records removed.");
  }
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => getPrisma().$disconnect());
